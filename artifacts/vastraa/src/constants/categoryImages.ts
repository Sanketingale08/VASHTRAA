/**
 * Resolves a high-quality image URL for any category, subcategory, or subtype.
 */
export function getCategoryOrSubcategoryImage(
  slugOrKey?: string | null,
  parentCategorySlug?: string | null,
  customImage?: string | null
): string {
  if (customImage && typeof customImage === "string" && customImage.trim()) {
    return customImage;
  }

  const norm = (slugOrKey || "").toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

  // 1. Direct subcategory match
  if (SAREE_SUBCATEGORY_IMAGES[norm]) {
    return SAREE_SUBCATEGORY_IMAGES[norm];
  }

  // 2. Direct category match
  if (SAREE_CATEGORY_IMAGES[norm]) {
    return SAREE_CATEGORY_IMAGES[norm];
  }

  // 3. Parent category match
  if (parentCategorySlug) {
    const parentNorm = parentCategorySlug.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-");
    if (SAREE_CATEGORY_IMAGES[parentNorm]) {
      return SAREE_CATEGORY_IMAGES[parentNorm];
    }
  }

  // 4. Deterministic fallback from gallery based on slug hash
  if (norm) {
    let hash = 0;
    for (let i = 0; i < norm.length; i++) {
      hash = (hash << 5) - hash + norm.charCodeAt(i);
      hash |= 0;
    }
    const idx = Math.abs(hash) % GALLERY_FALLBACKS.length;
    return GALLERY_FALLBACKS[idx];
  }

  return "/images/hero-paithani-1.png";
}

